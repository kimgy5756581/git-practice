package itm.comlang;

/**
 * 미로의 한 칸(cell)에 들어갈 수 있는 모든 객체가 구현하는 인터페이스.
 * 무기, 몬스터, 포션, 문, 빈칸, 열쇠가 모두 이 인터페이스를 구현한다.
 *
 * 이들이 공통으로 가지는 '상태(field)'는 거의 없지만, 두 가지 공통 '행동'이 있다:
 *   1) 화면에 어떤 글자로 보이는가        -> getSymbol()
 *   2) CSV 파일에 어떤 문자열로 저장되는가 -> toCsv()
 * 공유할 상태가 없으므로 부모 '클래스'가 아니라 '인터페이스'로 묶는 것이 적절하다.
 * 이 인터페이스 덕분에 Room은 칸의 실제 종류를 몰라도 똑같이 다룰 수 있다(다형성).
 */
public interface Drawable {

    /** 방을 화면에 그릴 때 이 칸에 출력할 한 글자 */
    char getSymbol();

    /** 방 상태를 CSV로 저장할 때 이 칸을 나타내는 문자열 (예: 몬스터는 "O:5") */
    String toCsv();
}
